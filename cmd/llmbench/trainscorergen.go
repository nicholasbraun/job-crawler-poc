// This file renders pagegate's generated weights table (ADR-0049, #300). It is the
// only thing in the tree that writes internal/pagegate/posting_score_weights_gen.go,
// and everything it emits is a pure function of the fitted model: keys sorted, values
// at a fixed precision, no timestamp, no host name, no run metadata of any kind --
// internal/geo's generator makes the same point, that a generation stamp would break
// byte-identical regeneration.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"math"
	"slices"
	"strconv"
)

// weightPrecision is the number of decimal places a weight, the intercept and the
// threshold are emitted with -- and, just as importantly, the precision the trainer
// ROUNDS TO before it ranks the Score Vocabulary and before it chooses the operating
// point. Rounding first is what makes regeneration reproducible on a machine that is
// not the one that committed the artifact: Go permits a floating-point multiply and
// add to be fused into a single rounding and whether it is differs by architecture, so
// raw weights can differ in their last bits between a developer's machine and CI.
// Six places then leaves a 1-ulp difference having to cross a 5e-7 boundary before it
// can move a byte.
const weightPrecision = 6

// weightScale is 10^weightPrecision, the multiplier the rounding is done through.
const weightScale = 1e6

// roundWeight rounds to weightPrecision, half away from zero. The negative-zero fold
// is not cosmetic: -0.0 and 0.0 are equal in Go but format differently, so without it
// a weight that rounded down from below would emit "-0.000000" and the artifact would
// depend on the sign of a value that means nothing.
func roundWeight(w float64) float64 {
	r := math.Round(w*weightScale) / weightScale
	if r == 0 {
		return 0
	}
	return r
}

// floorWeight rounds DOWN to weightPrecision. It is used for the threshold alone,
// where rounding toward the permissive side is the difference between a detail row
// surviving the cut by a whisker and being lost to it (ADR-0049).
func floorWeight(w float64) float64 { return math.Floor(w*weightScale) / weightScale }

// formatWeight renders one number at the committed precision. strconv rather than
// fmt so the format is fixed at the call site and cannot be widened by a stray verb.
func formatWeight(w float64) string {
	return strconv.FormatFloat(w, 'f', weightPrecision, 64)
}

// weightsArtifact is everything the generated file states, including what it states
// about its own provenance. The population counts are substituted from the run rather
// than written into the template, so the file's prose cannot go stale against the
// Gold Set it was fitted on.
type weightsArtifact struct {
	Model     scorerModel
	Threshold float64
	// ScorableRows is how many Extract Gold Set rows the fit ran over: every row with
	// a valid, non-ambiguous label.
	ScorableRows int
	// Hosts is how many distinct hosts those rows sit on. It is the number that makes
	// the leakage guard necessary, so the artifact says it out loud.
	Hosts int
}

// renderWeightsSource renders posting_score_weights_gen.go. The bytes go through
// go/format so `gofmt -l` stays empty and a malformed render fails HERE rather than at
// the next build.
func renderWeightsSource(a weightsArtifact) ([]byte, error) {
	names := make([]string, 0, len(a.Model.Weights))
	for name := range a.Model.Weights {
		names = append(names, name)
	}
	// Sorted, never ranged out of the map: Go randomizes map iteration, and an
	// artifact whose key order moved between runs could never be guarded by
	// byte-for-byte regeneration.
	slices.Sort(names)

	var b bytes.Buffer
	b.WriteString(weightsHeader)
	fmt.Fprintf(&b, weightsTableDoc, a.ScorableRows, len(a.Model.vocabularyWords()), a.Hosts)
	b.WriteString("var scoreWeights = map[string]float64{\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(name), formatWeight(a.Model.Weights[name]))
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, weightsInterceptDoc, formatWeight(a.Model.Intercept))
	fmt.Fprintf(&b, weightsThresholdDoc, formatWeight(a.Threshold))

	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated weights: %w", err)
	}
	return src, nil
}

// weightsHeader is the file's fixed preamble: the generated-code marker Go tooling
// reads, the package clause, and the directive that regenerates it.
//
// The directive runs with internal/pagegate as its working directory, so BOTH paths
// are relative to that -- an earlier draft named only the output and would have
// resolved the input's repo-root-relative default to a path inside the package.
const weightsHeader = `// Code generated by "llmbench train-scorer"; DO NOT EDIT.

package pagegate

// The directive regenerates this file from the committed Extract Gold Set. It runs
// with this package's directory as its working directory, so both paths are relative
// to that. No CI step runs "go generate" -- the standing guard is instead that
// regenerating must reproduce this file byte for byte
// (TestTrainScorerReproducesTheCommittedWeights), so a weight can only move by a Gold
// Set change or a trainer change, both visible in the same diff.
//go:generate go run ../../cmd/llmbench train-scorer -in ../../cmd/llmbench/extract-goldset/goldset.jsonl -out posting_score_weights_gen.go

`

// weightsTableDoc is the table's interface comment, taking the scorable row count,
// the Score Vocabulary size and the host count.
const weightsTableDoc = `// scoreWeights is the Score Vocabulary and the structural Score Signal weights, keyed
// by the exact names Signals emits (ADR-0049). It is the one part of pagegate that is
// fitted rather than argued, which is why it is data a human reads rather than a rule a
// human reasons about -- read it and check that it weighs the words a posting uses, not
// the words one sampled employer uses.
//
// Fitted over the %d scorable rows of the committed Extract Gold Set, holding %d Score
// Vocabulary words. No entry is a word of any host in that set: the exclusion is applied
// by the trainer and re-derived independently by a guard test, because those rows sit on
// only %d hosts and a blind fit would learn one sampled employer's boilerplate.
//
// Generated Go source rather than an embedded data file, and that is a deliberate
// deviation from the repo's one precedent, internal/geo (ADR-0031): parseGazetteer
// silently skips a malformed row, and a rule deciding spend on every walked page must
// not be able to boot with a quietly truncated Score Vocabulary. Generated source fails
// at compile time instead.
`

// weightsInterceptDoc is the intercept's interface comment, taking its value.
const weightsInterceptDoc = `// scoreIntercept is the fitted intercept: the Posting Score, before the logistic
// squash, of a page carrying no weighted Score Signal at all.
const scoreIntercept = %s

`

// weightsThresholdDoc is VetoThreshold's interface comment, taking its value.
const weightsThresholdDoc = `// VetoThreshold is the Posting Score at or above which the Learned Veto lets a page
// through (ADR-0049). It is a value in Score's [0,1] space.
//
// Compiled in beside the weights and deliberately NOT a config field: it is the
// operating point THIS training run chose under the zero-detail-loss constraint -- the
// deepest cut that loses none of the detail rows the Positive Evidence rung accepts on
// the committed Extract Gold Set -- and letting it drift independently of the weights it
// was chosen against would mean running an operating point nobody measured.
const VetoThreshold float64 = %s
`
