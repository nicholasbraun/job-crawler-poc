// boundaryCensusWeight is a CENSUS boundary drawing's row weight. It is exactly 1
// because every page the drawing's half of the disagreement holds is taken, so each
// row's inclusion probability is 1 and its inverse is 1. There is no accept-share
// correction to apply -- a census describes no stream, so there is no population to
// weight toward -- and the per-drawing weight balance therefore holds by construction.
//
// It is NOT every Boundary Stratum row's weight. A STRATIFIED Boundary Stratum
// (selectionStratified, ADR-0049) samples its bands, so its rows carry the inverse of
// their own selection probability, normalized to the drawing's row count. Weighting a
// sampled row 1 anyway would make any weighted read over the stratum describe the
// enriched sample while claiming to describe the drop set. A band whose quota does not
// bind is the one case where the two coincide, and it coincides by arithmetic rather
// than by exception: taking a band whole makes N_c/n_c exactly 1.
const boundaryCensusWeight = 1.0

// selectionDesign is HOW a boundary design turns the disagreement into rows. It is a
// field of the design rather than a flag, for boundaryCandidateConfig's reason: a
// stratum is claimed by exactly one design and therefore by exactly one selection
// design, which is how a committed row states not just which PAIR drew it but under
// which inclusion probabilities. Mixing two selection designs inside one stratum is
// what makes a weighted estimate over it unrecoverable.
type selectionDesign string

const (
	// selectionCensus takes every page of the half the design draws, at
	// boundaryCensusWeight.
	selectionCensus selectionDesign = "census"
	// selectionStratified samples the drop set in bands and weights each row by the
	// inverse of its selection probability (ADR-0049).
	selectionStratified selectionDesign = "stratified"
)

// boundaryBands is the fixed print / iteration order of a stratified drawing's bands.
// The order is the argument's: the live-accept half first, then the two score bands from
// the cut downwards.
var boundaryBands = []goldBand{bandAccepted, bandNear, bandDeep}

const (
	// defaultVetoNearBand is the score width below pagegate.VetoThreshold that counts
	// as "just below the cut". It is a FLAG's default rather than a constant use: what
	// the bands MEAN is the design and may not drift, but where "near" ends is a
	// judgement an operator re-reads off the report's band populations.
	//
	// The judgement is stated as a SHARE of the sub-threshold range rather than as an
	// absolute score, because the threshold is regenerated by every refit while an
	// absolute width is not. A width that outlives its threshold does not merely lose
	// its meaning: validate() refuses a band at or above the cut, so the verb's own
	// default becomes ILLEGAL the moment a refit lands below it -- which is exactly what
	// happened when the Extract Gold Set grew to 737 rows and the cut fell from 0.605395
	// to 0.165048. docs/improving-the-posting-score.md names that failure mode outright.
	//
	// A third is not a new judgement. The 0.20 this drawing shipped with was chosen at a
	// VetoThreshold of 0.605395, and 0.605395/3 = 0.201798 -- the same operating point to
	// within one percent. The derived form REPRODUCES the judgement that was made, in a
	// shape no retrain can invalidate. An operator still overrides it with -near-band;
	// only the default is scale-free.
	defaultVetoNearBand = pagegate.VetoThreshold / 3
	// defaultVetoAcceptedRows, defaultVetoNearRows and defaultVetoDeepRows are the three
	// bands' quotas. They are COUNTS, not shares, because the human confirmation budget
	// is absolute and does not scale with the frame -- which is also why no band may be
	// censused here. Over the CLOSED capture window (18,233 framed pages, a 12,036-row
	// drop set banded 2,025 / 370 / 9,641 -- read against the weights and the 0.20 band
	// edge that shipped BEFORE the 737-row refit, so the band populations have moved
	// even though the frame has not) a census of the accepted band alone would owe
	// 2,025 Blind Confirmations and the drawing 2,145; these defaults draw
	// 100 + 80 + 40 = 220, the order of a pass a person finishes. The quotas are a
	// confirmation budget and do not move with a refit.
	//
	// 100 is what the accepted band's question costs to answer. A 100-row sample of 2,025
	// pins that band's false-drop rate to a standard error of at most ~5 points --
	// sqrt(p(1-p)/100) * sqrt(1925/2024) is 4.9pp at p=0.5 and 2.9pp at p=0.1 -- and that
	// sampling variance is dominated by a bias no quota can remove: which pages land in
	// this band at all is decided by the live extractor's verdict, which runs at 0.454
	// precision against human labels (ADR-0049). Spending the confirmation budget against
	// the smaller error while the larger one stands is not a trade worth making.
	defaultVetoAcceptedRows = 100
	defaultVetoNearRows     = 80
	defaultVetoDeepRows     = 40
)

// boundaryBaselineConfig is TODAY'S blanket accept: the Extract Gate as it behaved
// before ADR-0044's Positive Evidence rung. RequirePositiveEvidence is set FALSE
// explicitly rather than left at its default so this keeps meaning "the previous
// behaviour" after #264 flips that default on.
//
// LearnedVeto is pinned FALSE for the same reason (ADR-0049): the baseline is the
// pre-ADR-0044 gate, which had no rung 9 at all, and a default flip that quietly armed
// one here would make AuditFalseDrops attribute veto-caused drops to the baseline's
// reject rungs.
func boundaryBaselineConfig() crawler.LLMGateConfig {
	cfg := crawler.DefaultLLMGateConfig()
	cfg.RequirePositiveEvidence = false
	cfg.LearnedVeto = false
	return cfg
}

// boundaryCandidateConfig is the tiered Positive Evidence rule as the gate ships it
// TODAY (ADR-0044, internal/pagegate/positive_evidence.go). TRUE is set explicitly
// for the same reason the baseline sets FALSE.
//
// It is no longer the rule that DREW this stratum. The draw was taken against #258's
// rule, and #257 widened that rule to the false-drops the stratum measured, so the
// committed rows are a HISTORICAL disagreement set: 29 of them extract under the rule
// this function now returns. The stratum was kept rather than re-drawn -- re-drawing
// discards the recovered postings, which are the evidence, and owes 188 fresh human
// confirmations -- and TestCommittedBoundaryRecoveryLedger is the ledger of what
// changed. A fresh DRAW (goldset-sample-boundary) still uses this function and still
// gets today's boundary, which is why it reads the shipping rule rather than a pinned
// copy of #258's.
//
// The rule lives HERE, in code, rather than in a -gate-config flag: a flag would let
// a later run silently redefine the boundary, and the drawn rows would then claim a
// boundary nobody could re-derive.
//
// LearnedVeto is pinned FALSE, and that pin is load-bearing beyond the draw (ADR-0049).
// This function is also how the trainer and two guards name "the pages the Positive
// Evidence rung accepts": rung 8's accept population is by definition PRE-veto, since
// the veto only ever prunes it. Left at its default, the day EXTRACT_LEARNED_VETO's
// default flips, scorerSamples would fit its operating point against the veto's own
// survivors, TestCommittedThresholdLosesNoDetailRowThePositiveEvidenceRungAccepts would
// become a tautology, and the subtractive-only guard's OFF arm would be a second copy
// of its ON arm.
func boundaryCandidateConfig() crawler.LLMGateConfig {
	cfg := crawler.DefaultLLMGateConfig()
	cfg.RequirePositiveEvidence = true
	cfg.LearnedVeto = false
	return cfg
}

